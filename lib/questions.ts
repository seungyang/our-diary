/** 오늘의 질문 — 날짜에 따라 정해진다. 서버든 클라이언트든 같은 답이 나온다. */
export function questionFor(ymd: string): { index: number; text: string } {
  const n = Math.abs(daysBetween(EPOCH, ymd));
  const index = n % QUESTIONS.length;
  return { index, text: QUESTIONS[index] };
}
